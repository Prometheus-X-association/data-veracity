#!/bin/sh
# Runtime base path configuration for the SPA (run by the nginx image's
# /docker-entrypoint.sh before nginx starts).
#
# The app is built with the placeholder base '/__DVA_BASE_PATH__/'. This script
# copies the pristine build into the web root, replaces the placeholder with
# $BASE_PATH (default: '/'), and writes an nginx snippet so the app works both
# when a reverse proxy strips the prefix and when it forwards it unchanged.
#
# Example: BASE_PATH=/worker/vlamanager-frontend
set -eu

PLACEHOLDER='/__DVA_BASE_PATH__/'
SRC_DIR=/opt/app/dist
WEB_ROOT=/usr/share/nginx/html
SNIPPET=/etc/nginx/base-path.conf

base="${BASE_PATH:-/}"
# Normalise to exactly one leading and one trailing slash
base="/$(printf '%s' "$base" | sed -e 's#^/*##' -e 's#/*$##')/"
base=$(printf '%s' "$base" | sed 's#^//$#/#')

case "$base" in
  *[!A-Za-z0-9._~/-]*)
    echo "base-path.sh: invalid BASE_PATH '$BASE_PATH' (allowed: A-Z a-z 0-9 . _ ~ / -)" >&2
    exit 1 ;;
esac

echo "base-path.sh: serving app under '$base'"

# Start from the pristine build every time so container restarts stay idempotent
rm -rf "${WEB_ROOT:?}"/*
cp -a "$SRC_DIR"/. "$WEB_ROOT"/
find "$WEB_ROOT" -type f \( -name '*.html' -o -name '*.js' -o -name '*.css' -o -name '*.json' \) \
  -exec sed -i "s#${PLACEHOLDER}#${base}#g" {} +

# If the proxy does NOT strip the prefix, strip it inside nginx instead
if [ "$base" = "/" ]; then
  : > "$SNIPPET"
else
  prefix="${base%/}"
  prefix_re=$(printf '%s' "$prefix" | sed 's#\.#\\.#g')
  cat > "$SNIPPET" <<EOF
# Generated by base-path.sh for BASE_PATH=${base}
rewrite ^${prefix_re}\$ ${base} redirect;
rewrite ^${prefix_re}(/.*)\$ \$1 last;
EOF
fi
